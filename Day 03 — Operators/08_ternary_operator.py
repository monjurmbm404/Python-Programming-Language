"""
========================================
08_ternary_operator.py
========================================
Ternary Operator:

Syntax:
value_if_true if condition else value_if_false
"""

a = 10
b = 20

result = "A is greater" if a > b else "B is greater"
print(result)

# Another example
age = 18
status = "Adult" if age >= 18 else "Minor"
print(status)