"""
========================================
02_assignment_operators.py
========================================
Assignment Operators:

=   Assign
+=  Add and assign
-=  Subtract and assign
*=  Multiply and assign
/=  Divide and assign
%=  Modulus and assign
"""

x = 10

x += 5   # x = x + 5
print(x)

x -= 3   # x = x - 3
print(x)

x *= 2   # x = x * 2
print(x)

x /= 4   # x = x / 4
print(x)

x %= 3   # x = x % 3
print(x)