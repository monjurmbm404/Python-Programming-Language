"""
========================================
01_arithmetic_operators.py
========================================
Arithmetic Operators:

+   Addition
-   Subtraction
*   Multiplication
/   Division
%   Modulus
**  Exponent
//  Floor Division
"""

a = 10
b = 3

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Modulus:", a % b)
print("Exponent:", a ** b)
print("Floor Division:", a // b)