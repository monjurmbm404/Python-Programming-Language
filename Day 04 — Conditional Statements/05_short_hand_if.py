"""
========================================
05_short_hand_if.py
========================================
Short-hand if (Ternary style in Python):

✔ One-line if-else
"""

age = 22

# Short-hand if-else
result = "Adult" if age >= 18 else "Minor"

print(result)

# Another example
number = 15
status = "Positive" if number > 0 else "Negative"
print(status)