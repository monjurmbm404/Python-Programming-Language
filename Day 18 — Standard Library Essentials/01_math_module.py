import math

# Basic functions
print("Square root:", math.sqrt(25))
print("Power:", math.pow(2, 3))

# Rounding functions
print("Ceil:", math.ceil(4.2))
print("Floor:", math.floor(4.8))

# Constants
print("Pi value:", math.pi)
print("Euler's number:", math.e)

# Factorial
print("Factorial of 5:", math.factorial(5))